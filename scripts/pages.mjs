import { SITE_CONFIG as cfg } from "../js/config.js";

const e = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (char) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        char
      ],
  );
const projectPath = (root, slug) => `${root}projects/${slug}/index.html`;
const external = (label, url, className = "") =>
  url
    ? `<a class="${className}" href="${e(url)}" target="_blank" rel="noopener noreferrer">${e(label)}</a>`
    : "";
const heading = (first, second) =>
  `<h2 class="section-heading"><span class="line"><span>${e(first)}</span></span><span class="line"><span>${e(second)}</span></span></h2>`;
const ticker = (text) =>
  `<div class="ticker" aria-hidden="true"><div class="ticker__run">${e(`${text} • `.repeat(4))}</div></div>`;
const badge = (project) =>
  `<span class="status-badge ${project.released ? "" : "is-progress"}">${e(project.status)}</span>`;

export function picture(
  image,
  alt,
  root,
  manifest,
  { lazy = true, sizes = "(max-width: 420px) 76vw, 320px" } = {},
) {
  const meta = manifest[image];
  if (!meta?.sources.length)
    throw new Error(`Run npm run images: missing image metadata for ${image}`);
  return `<picture><source type="image/webp" srcset="${meta.sources.map((source) => `${root}${source.src} ${source.width}w`).join(", ")}" sizes="${e(sizes)}"><img src="${root}${image}" alt="${e(alt)}" width="${meta.width}" height="${meta.height}" loading="${lazy ? "lazy" : "eager"}" ${lazy ? "" : 'fetchpriority="high"'} decoding="async"></picture>`;
}

