function architecture(arch) {
  const positions = [
    { x: 18, y: 28 },
    { x: 287, y: 28 },
    { x: 287, y: 218 },
    { x: 18, y: 218 },
  ];
  const nodeMap = new Map(
    arch.nodes.map((node, index) => [
      node.id,
      { ...node, ...positions[index] },
    ]),
  );
  const wires = arch.edges
    .map(([from, to, label]) => {
      const a = nodeMap.get(from),
        b = nodeMap.get(to);
      const dx = b.x - a.x,
        dy = b.y - a.y;
      const scale = 1 / Math.max(Math.abs(dx) / 107.5, Math.abs(dy) / 37);
      return `<path class="arch-wire" d="M ${a.x + 107.5 + dx * scale} ${a.y + 37 + dy * scale} L ${b.x + 107.5 - dx * scale} ${b.y + 37 - dy * scale}" marker-end="url(#arch-arrow)"><title>${e(label)}</title></path>`;
    })
    .join("");
  const nodes = arch.nodes
    .map(
      (node, i) =>
        `<g class="arch-node-group" data-node="${node.id}" transform="translate(${positions[i].x}, ${positions[i].y})" aria-label="${e(node.name)}"><g class="arch-node-visual"><rect class="arch-node-box" width="215" height="74" rx="3"></rect><text class="arch-node-tag" x="12" y="20">${e(node.tag)}</text><text class="arch-node-title" x="12" y="42">${e(node.name)}</text><text class="arch-node-sub" x="12" y="58">${e(node.tech)}</text></g></g>`,
    )
    .join("");
  const details = arch.nodes
    .map(
      (node) =>
        `<article class="arch-hud" id="detail-${node.id}" data-detail="${node.id}"><div class="arch-hud__header"><span class="arch-hud__tag">${e(node.tag)}</span><h4 class="arch-hud__name">${e(node.name)}</h4><span class="arch-hud__tech">${e(node.tech)}</span></div><p class="arch-hud__desc">${e(node.desc)}</p><div class="arch-hud__meta-grid"><div class="arch-meta-item"><span>Interface</span><b>${e(node.protocol)}</b></div><div class="arch-meta-item"><span>Design</span><b>${e(node.behavior)}</b></div></div><div class="arch-console-log"><p><span class="log-prompt">Example event:</span> ${e(node.log.replace(/^Example: /, ""))}</p></div></article>`,
    )
    .join("");
  return `<div class="arch-console" id="arch-console"><div class="arch-topbar"><div class="arch-badge-group"><span class="arch-spec-pill">${e(arch.specId)}</span><span class="arch-status">ILLUSTRATIVE MODEL</span></div><div class="arch-controls" hidden><div class="arch-views-nav" aria-label="Architecture views">${[
    ["schematic", "Topology"],
    ["pipeline", "Pipeline"],
    ["highlights", "Decisions"],
  ]
    .map(
      ([view, label]) =>
        `<button type="button" class="arch-tab-btn" id="tab-${view}" data-view="${view}">${label}</button>`,
    )
    .join("")}</div></div></div>
    <p class="arch-disclaimer">A documented system model. Walkthroughs are illustrative; they do not contact or verify a live service.</p>
    <section class="arch-view-panel" id="view-schematic"><h3 class="arch-panel-title">Topology</h3><div class="arch-workbench"><div class="arch-canvas-wrap"><div class="arch-diagram-scroll" tabindex="0" role="region" aria-label="System diagram. Scroll horizontally on smaller screens."><svg class="arch-svg-stage" viewBox="0 0 520 320" role="group" aria-label="System components"><defs><marker id="arch-arrow" markerWidth="6" markerHeight="6" refX="5" refY="3" orient="auto"><path d="M0 0 L6 3 L0 6 Z" fill="currentColor"></path></marker></defs>${wires}${nodes}</svg></div><ul class="arch-connections">${arch.edges.map(([from, to, label]) => `<li><b>${e(nodeMap.get(from).name)} → ${e(nodeMap.get(to).name)}</b>: ${e(label)}</li>`).join("")}</ul></div><div class="arch-details">${details}</div></div><p id="node-status" class="sr-only" role="status" aria-atomic="true"></p></section>
    <section class="arch-view-panel" id="view-pipeline"><h3 class="arch-panel-title">Pipeline</h3><div class="arch-pipeline-wrap">${arch.pipeline.map((step) => `<div class="arch-pipeline-step"><b>${step.step}</b><h4>${e(step.name)}</h4><p>${e(step.desc)}</p></div>`).join("")}</div></section>
    <section class="arch-view-panel" id="view-highlights"><h3 class="arch-panel-title">Decisions</h3><div class="arch-highlights-wrap">${arch.highlights.map((item) => `<div class="arch-highlight-card"><span>${e(item.label)}</span><p>${e(item.value)}</p></div>`).join("")}</div></section>
    <div class="arch-demo" hidden><label for="flow-path">Example path</label><select id="flow-path">${arch.flows.map((flow) => `<option value="${flow.steps.join(",")}">${e(flow.name)}</option>`).join("")}</select><button type="button" class="arch-sim-btn" id="run-sim-btn">Show example flow</button><p id="flow-status" role="status" aria-atomic="true"></p></div>
  </div>`;
}

